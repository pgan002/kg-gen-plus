import urllib.parse
import html
import unicodedata
from dataclasses import dataclass, field
from typing import List, Optional
from rapidfuzz import fuzz


@dataclass
class EvalEntity:
    surface_form: str
    uri: Optional[str] = None


@dataclass
class EvalTriple:
    subject: EvalEntity
    predicate: EvalEntity
    object: EvalEntity


@dataclass
class EvalGraph:
    triples: List[EvalTriple] = field(default_factory=list)


def normalize_text(text: str) -> str:
    """
    Normalizes text by unescaping HTML, unquoting URLs,
    replacing underscores with spaces, and applying Unicode normalization.
    """
    if not text:
        return ""
    # unescape html entities
    text = html.unescape(text)
    # unquote url encodings (handles %20, etc.)
    text = urllib.parse.unquote(text)
    # replace underscores with spaces
    text = text.replace("_", " ")
    # normalize unicode
    text = unicodedata.normalize("NFKC", text)
    return text.lower().strip()


def evaluate_graph(
    generated_graph: EvalGraph, gold_graph: EvalGraph, match_threshold: float = 90.0
):
    """
    Evaluates the generated graph against a gold standard graph using RapidFuzz.

    Args:
        generated_graph (EvalGraph): The graph generated by the model.
        gold_graph (EvalGraph): The gold standard data.
        match_threshold (float): The minimum similarity score (0-100) for two triples to match.

    Returns:
        dict: A dictionary containing precision, recall, and F1 score.
    """

    # Extract and normalize triples from the generated graph, including URIs
    # Keep original r for returning triples later
    generated_triples_full = [
        (
            r,
            {
                "subject": normalize_text(r.subject.surface_form),
                "predicate": normalize_text(r.predicate.surface_form),
                "predicate_uri": r.predicate.uri,
                "object": normalize_text(r.object.surface_form),
            },
        )
        for r in generated_graph.triples
    ]

    # Extract and normalize triples from the gold standard data, including URIs
    gold_triples_full = [
        (
            t,
            {
                "subject": normalize_text(t.subject.surface_form),
                "predicate": normalize_text(t.predicate.surface_form),
                "predicate_uri": t.predicate.uri,
                "object": normalize_text(t.object.surface_form),
            },
        )
        for t in gold_graph.triples
    ]

    true_positive_triples = []
    matched_gold_indices = set()
    matched_gen_indices = set()

    for gen_idx, (gen_r, gen_triple) in enumerate(generated_triples_full):
        best_score = -1
        best_match_idx = -1

        for idx, (gold_t, gold_triple) in enumerate(gold_triples_full):
            if idx in matched_gold_indices:
                continue

            # Check predicates first
            p_uri_match = False
            p_score = None

            # If both have URIs, they must match exactly
            if gen_triple["predicate_uri"] and gold_triple["predicate_uri"]:
                if gen_triple["predicate_uri"] == gold_triple["predicate_uri"]:
                    p_uri_match = True
                    p_score = 100.0
            if p_score is None:
                # Fall back to fuzzy text matching if URIs are missing
                class_assert_predicates = {
                    "instance of",
                    "is a",
                    "type",
                    "has type",
                    "class",
                }
                if (
                    gen_triple["predicate"] in class_assert_predicates
                    and gold_triple["predicate"] in class_assert_predicates
                ):
                    p_score = 100.0
                else:
                    p_score = fuzz.ratio(
                        gen_triple["predicate"], gold_triple["predicate"]
                    )

            # If predicate doesn't match threshold (and didn't match via URI), skip
            if not p_uri_match and p_score < match_threshold:
                continue

            # Check subject and object
            s_score = fuzz.ratio(gen_triple["subject"], gold_triple["subject"])
            o_score = fuzz.ratio(gen_triple["object"], gold_triple["object"])

            # Check if all components meet the threshold
            if s_score >= match_threshold and o_score >= match_threshold:
                avg_score = (s_score + p_score + o_score) / 3
                if avg_score > best_score:
                    best_score = avg_score
                    best_match_idx = idx

        if best_match_idx != -1:
            true_positive_triples.append((gen_r, gold_triples_full[best_match_idx][0]))
            matched_gold_indices.add(best_match_idx)
            matched_gen_indices.add(gen_idx)

    false_positive_triples = [
        (
            gen_r.subject.surface_form,
            gen_r.predicate.surface_form,
            gen_r.object.surface_form,
        )
        for i, (gen_r, _) in enumerate(generated_triples_full)
        if i not in matched_gen_indices
    ]
    false_negative_triples = [
        (
            gold_t.subject.surface_form,
            gold_t.predicate.surface_form,
            gold_t.object.surface_form,
        )
        for i, (gold_t, _) in enumerate(gold_triples_full)
        if i not in matched_gold_indices
    ]

    true_positives = len(true_positive_triples)
    false_positives = len(false_positive_triples)
    false_negatives = len(false_negative_triples)

    # Calculate precision, recall, and F1 score
    precision = (
        true_positives / len(generated_triples_full)
        if len(generated_triples_full) > 0
        else 0.0
    )
    recall = (
        true_positives / len(gold_triples_full) if len(gold_triples_full) > 0 else 0.0
    )
    f1_score = (
        2 * (precision * recall) / (precision + recall)
        if (precision + recall) > 0
        else 0.0
    )

    return {
        "precision": precision,
        "recall": recall,
        "f1_score": f1_score,
        "true_positives": true_positives,
        "false_positives": false_positives,
        "false_negatives": false_negatives,
        "true_positive_triples": true_positive_triples,
        "false_positive_triples": false_positive_triples,
        "false_negative_triples": false_negative_triples,
    }


class GraphEvaluator:
    """
    A class to handle evaluation over a dataset of graphs, keeping track of
    running totals and calculating aggregated macro/micro metrics.
    """

    def __init__(self, match_threshold: float = 90.0):
        self.match_threshold = match_threshold
        self.results: List[dict] = []
        self.total_tp = 0
        self.total_fp = 0
        self.total_fn = 0

    def evaluate(self, generated_graph: EvalGraph, gold_graph: EvalGraph) -> dict:
        """Evaluates a single graph pair and updates running totals."""
        result = evaluate_graph(generated_graph, gold_graph, self.match_threshold)
        self.results.append(result)

        self.total_tp += result["true_positives"]
        self.total_fp += result["false_positives"]
        self.total_fn += result["false_negatives"]

        return result

    def get_aggregated_results(self) -> dict:
        """Calculates and returns the aggregated metrics across all evaluated graphs."""
        if not self.results:
            return {}

        # Micro metrics (aggregate raw counts first, then calculate metrics)
        micro_precision = (
            self.total_tp / (self.total_tp + self.total_fp)
            if (self.total_tp + self.total_fp) > 0
            else 0.0
        )
        micro_recall = (
            self.total_tp / (self.total_tp + self.total_fn)
            if (self.total_tp + self.total_fn) > 0
            else 0.0
        )
        micro_f1 = (
            (2 * micro_precision * micro_recall) / (micro_precision + micro_recall)
            if (micro_precision + micro_recall) > 0
            else 0.0
        )

        # Macro metrics (average of the per-graph metrics)
        num_graphs = len(self.results)
        macro_precision = sum(r["precision"] for r in self.results) / num_graphs
        macro_recall = sum(r["recall"] for r in self.results) / num_graphs
        macro_f1 = sum(r["f1_score"] for r in self.results) / num_graphs

        return {
            "total_graphs_evaluated": num_graphs,
            "total_true_positives": self.total_tp,
            "total_false_positives": self.total_fp,
            "total_false_negatives": self.total_fn,
            "micro_precision": micro_precision,
            "micro_recall": micro_recall,
            "micro_f1": micro_f1,
            "macro_precision": macro_precision,
            "macro_recall": macro_recall,
            "macro_f1": macro_f1,
        }
